// 변수 선언 후 초기화하고 사용해야 함. 초기화하지 않고 사용하면 쓰레기값이 들어있을 수 있음

// scanf() 함수 : 표준입력함수 ==> DDoS 공격에 취약함, 입력값이 예상보다 많으면 버퍼 오버플로우 발생 가능
// security warning 방지 방법
//		1. scanf_s() 함수 사용
//		2. 첫 줄에 #define _CRT_SECURE_NO_WARNINGS 추가
//		3. Visual Studio 프로젝트 속성에서 C/C++ -> 코드 생성 -> 보안 개발 모드 사용을 "아니오(/GS-)"로 변경

// 버퍼에 남아있는 개행문자 제거해야 함.
// scanf() 함수는 입력값을 버퍼에 저장하고, 엔터키를 누르면 개행문자('\n')가 버퍼에 남아있게 됨
// %c 와 같이 한 문자를 입력받는 경우, 버퍼에 남아있는 개행문자를 읽어와서 변수에 저장하게 되어 원하는 결과를 얻지 못할 수 있음

