//#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>

int main() {
	int age = 0;			// 실수를 저장할 수 있는 4byte 크기의 저장공간을 만들어
	char gender = 0;		// 한 문자를 저장할 수 있는 1byte 크기의 저장공간을 만들어
	double weight = 0;		// 실수를 저장할 수 있는 8byte 크기의 저장공간을 만들어
	char name[10] = { 0 };	// 문자열를 저장할 수 있는 10byte 크기의 저장공간을 만들어
	
	printf("나이를 입력 : ");
	scanf("%d", &age);					//scanf("서식", &변수명), &(주소연산자) age의 주소를 찾아가서 그 주소에 있는 값을 덮어써서 바꿔야하기 때문에 반드시 주소 연산자를 사용해야 함
										// scanf() 함수는 키보드로 입력한 값을 메모리에 저장하는 함수이기 때문에, 입력한 값을 저장할 메모리 공간의 주소를 알아야 함.
										// 따라서 scanf() 함수는 변수의 주소를 매개변수로 전달해야 함
	//scanf_s("%d", &age, sizeof(age));

	getchar();							// 입력버퍼에서 한 문자를 읽어서 버려라
	//while (getchar() != '\n');


	printf("성별 입력 : ");
	scanf(" %c", &gender);

	printf("체중 입력 : ");
	scanf("%lf", &weight);

	printf("이름 입력 : ");
	scanf("%s", name);			// 문자열은 배열이기 때문에 주소연산자를 붙이지 않아도 됨. 배열에서 배열 이름은 주소. 따라서 배열 이름 앞에는 주소 연산자를 붙이지 않는다.

	printf("입력 나이는 : %d세 입니다.\n", age);
	printf("입력 성별은 : %c 입니다.\n", gender);
	printf("입력 체중은 : %lfkg 입니다.\n", weight);
	printf("입력 이름은 : %s 입니다.\n", name);

	return 0;
}

